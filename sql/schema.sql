-- Mock Stride: a stand-in for the Stride EHR used to test our SFTP import end to end.
-- Lives in its own schema in the DEMO Supabase project only. It never touches the
-- backend's tables; it only reads leads / stride_import_files for its screens.
-- Every row carries modified_at so an export can send "changes since the last one",
-- and deleted_at so a delete is exported once as Action=Delete, like real Stride.

create schema if not exists mock_stride;

create table if not exists mock_stride.locations (
  id bigint primary key,
  name text not null,
  address_1 text, city text, state text, zip text, phone text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  modified_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists mock_stride.users (
  id bigint primary key,
  first_name text not null,
  last_name text not null,
  email text, credentials text, npi text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  modified_at timestamptz not null default now(),
  deleted_at timestamptz
);

-- Real Stride ids are plain integers; start high so they never look like the
-- sandbox CSV ids.
create table if not exists mock_stride.patients (
  id bigint generated by default as identity (start with 900001) primary key,
  first_name text not null,
  last_name text not null,
  date_of_birth date,
  gender text,
  personal_email text,
  mobile_phone text,          -- 10 US digits; exported as (xxx) xxx-xxxx
  home_phone text,
  address_1 text, city text, state text, zip text,
  marketing_opt_in boolean not null default true,
  lead_id uuid,               -- set when created from one of our leads (display only)
  created_at timestamptz not null default now(),
  modified_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists mock_stride.cases (
  id bigint generated by default as identity (start with 700001) primary key,
  patient_id bigint not null references mock_stride.patients(id),
  title text not null,
  status text not null default 'A',
  created_at timestamptz not null default now(),
  modified_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists mock_stride.appointments (
  id bigint generated by default as identity (start with 9000001) primary key,
  patient_id bigint not null references mock_stride.patients(id),
  case_id bigint not null references mock_stride.cases(id),
  type_id bigint not null,
  type_name text not null,
  appt_date date not null,    -- clinic-local date
  start_time time not null,   -- clinic-local
  end_time time not null,
  status text not null default 'Unmarked',
  location_id bigint not null references mock_stride.locations(id),
  clinician_id bigint not null references mock_stride.users(id),
  place_of_service text not null default '11 - Office',
  payment_type text not null default 'Commercial',
  created_at timestamptz not null default now(),
  modified_at timestamptz not null default now(),
  deleted_at timestamptz
);

create table if not exists mock_stride.exports (
  id bigint generated always as identity primary key,
  started_at timestamptz not null,
  finished_at timestamptz,
  trigger text not null check(trigger in ('timer','button','full')),
  since timestamptz,          -- null = full export
  status text not null default 'running' check(status in ('running','sent','nothing','failed')),
  files jsonb not null default '[]'::jsonb,
  error text
);

-- One row: the watermark for "changes since the last successful export" and a
-- simple lock so two exports never overlap.
create table if not exists mock_stride.state (
  id integer primary key default 1 check(id = 1),
  last_success_at timestamptz,
  exporting_since timestamptz,
  auto_send boolean not null default true
);
insert into mock_stride.state(id) values(1) on conflict do nothing;

create index if not exists idx_mock_patients_modified on mock_stride.patients(modified_at);
create index if not exists idx_mock_appts_modified on mock_stride.appointments(modified_at);
create index if not exists idx_mock_appts_patient on mock_stride.appointments(patient_id);
create index if not exists idx_mock_cases_patient on mock_stride.cases(patient_id);

-- Not reachable through Supabase's public API; only the app's direct DB login.
alter table mock_stride.locations enable row level security;
alter table mock_stride.users enable row level security;
alter table mock_stride.patients enable row level security;
alter table mock_stride.cases enable row level security;
alter table mock_stride.appointments enable row level security;
alter table mock_stride.exports enable row level security;
alter table mock_stride.state enable row level security;
-- Supabase's API roles; plain Postgres (the demo server's own db) has neither.
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'anon')
     and exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on schema mock_stride from anon, authenticated;
  end if;
end $$;

