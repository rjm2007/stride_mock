-- Real Stride refuses two visits in one case at one start time ("Appointment Date+Case combination
-- already exists"). Without this, a Delete row (no Appointment Id) matched two visits on our server
-- and was skipped (2026-10-13 test round). Applied to the demo database on 2026-10-13.
create unique index if not exists appointments_one_per_case_slot
  on mock_stride.appointments(case_id, appt_date, start_time) where deleted_at is null;
